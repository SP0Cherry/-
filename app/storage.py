"""Server-side file storage for teaching materials.

Storage keys are generated by the server (uuid). Client filenames are NEVER
used to build server-side paths; they are stored as display names only.
"""
import os
import uuid

from flask import current_app
from werkzeug.utils import secure_filename


def extension_of(filename: str) -> str:
    # Derive from the raw basename (do NOT pass through secure_filename:
    # it strips CJK characters and can drop the leading dot, e.g.
    # "光合作用.md" -> "md"). The result is matched against an allowlist.
    basename = (filename or "").replace("\\", "/").rsplit("/", 1)[-1]
    if "." not in basename:
        return ""
    return basename.rsplit(".", 1)[-1].lower()


def is_allowed_file(filename: str, declared_mimetype: str) -> bool:
    ext = extension_of(filename)
    config = current_app.config
    if not ext or ext not in config["ALLOWED_EXTENSIONS"]:
        return False
    return declared_mimetype in config["ALLOWED_MIME_TYPES"].get(ext, set())


def _target_path(upload_root: str, class_id: int, ext: str) -> tuple[str, str]:
    directory = os.path.join(upload_root, str(class_id))
    os.makedirs(directory, exist_ok=True)
    name = uuid.uuid4().hex + (f".{ext}" if ext else "")
    return directory, name


def write_bytes(upload_root: str, class_id: int, ext: str, data: bytes) -> tuple[str, int]:
    """Persist raw bytes; return (stored_key, size_bytes)."""
    directory, name = _target_path(upload_root, class_id, ext)
    full_path = os.path.join(directory, name)
    with open(full_path, "wb") as handle:
        handle.write(data)
    stored_key = os.path.join(str(class_id), name)
    return stored_key.replace("\\", "/"), len(data)


def save_file_storage(file_storage, class_id: int) -> tuple[str, int]:
    """Persist an uploaded werkzeug FileStorage; return (stored_key, size)."""
    ext = extension_of(file_storage.filename)
    directory, name = _target_path(
        current_app.config["UPLOAD_ROOT"], class_id, ext
    )
    full_path = os.path.join(directory, name)
    file_storage.save(full_path)
    size = os.path.getsize(full_path)
    stored_key = os.path.join(str(class_id), name)
    return stored_key.replace("\\", "/"), size


def absolute_path(stored_key: str) -> str:
    return os.path.join(current_app.config["UPLOAD_ROOT"], stored_key)


def delete_stored(stored_key: str) -> None:
    try:
        os.remove(absolute_path(stored_key))
    except FileNotFoundError:
        pass
